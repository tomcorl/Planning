-- RPC pour charger toutes les données planning (bypass RLS pour l'affichage toutes entreprises)
CREATE OR REPLACE FUNCTION get_planning_data()
RETURNS JSONB LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  result JSONB;
BEGIN
  SELECT jsonb_build_object(
    'companies', (
      SELECT jsonb_agg(jsonb_build_object('id', c.id, 'nom', c.nom, 'chantier_colors', COALESCE(c.chantier_colors, ARRAY['#2563eb','#93c5fd','#eab308','#15803d','#6b7280','#f97316','#7dd3fc']::TEXT[])))
      FROM (
        SELECT id, nom, chantier_colors FROM companies WHERE id = 'batiouest'
      ) c
    ),
    'equipes', (
      SELECT jsonb_agg(jsonb_build_object('nom', e.nom, 'company_id', e.company_id, 'ordre', e.ordre, 'color', COALESCE(e.color, '#7dd3fc')))
      FROM (
        SELECT nom, company_id, ordre, color
        FROM equipes
        ORDER BY
          CASE company_id
            WHEN 'batiouest' THEN 1
            ELSE 2
          END, ordre
      ) e
    ),
    'chantiers', (SELECT jsonb_agg(to_jsonb(ch)) FROM chantiers ch),
    'conges', (SELECT jsonb_agg(to_jsonb(co)) FROM conges co),
    'custom_feries', (SELECT jsonb_agg(to_jsonb(cf)) FROM custom_feries cf)
  ) INTO result;
  RETURN result;
END;
$$;

-- RPC batch : sauvegarde toutes les données en 1 appel
